/** Drives ambient Aurora motion; respects the shared Reduce motion preference. */
val LocalAuroraMotion = compositionLocalOf { true }

@Composable
fun OriginTheme(
    themeMode: ThemeMode,
    dynamicColor: Boolean,
    reducedMotion: Boolean = false,
    content: @Composable () -> Unit
) {
    val context = androidx.compose.ui.platform.LocalContext.current
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        darkTheme -> OriginDarkColors
        else -> OriginLightColors
    }

    androidx.compose.runtime.CompositionLocalProvider(LocalAuroraMotion provides !reducedMotion) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = OriginTypography,
            shapes = OriginShapes,
            content = content
        )
    }
}
